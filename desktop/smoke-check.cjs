const fs = require('node:fs');
const path = require('node:path');

module.exports = async function smokeCheck(window, directory) {
  const evaluate = script => window.webContents.executeJavaScript(script);
  async function screenshot(name) {
    await new Promise(resolve => setTimeout(resolve, 150));
    const image = await window.webContents.capturePage({}, { stayHidden: true, stayAwake: true });
    if (image.isEmpty()) throw new Error('Desktop screenshot was empty.');
    fs.writeFileSync(path.join(directory, name), image.toPNG());
  }
  async function waitFor(expression) {
    for (let attempt = 0; attempt < 150; attempt++) {
      if (await evaluate(expression)) return;
      await new Promise(resolve => setTimeout(resolve, 40));
    }
    throw new Error(`Desktop check timed out: ${expression}`);
  }
  await waitFor("!!document.querySelector('.kc-page-heading h1')");
  if (await evaluate('Boolean(window.electronAPI)')) throw new Error('Legacy bridge leaked into redesign.');
  await evaluate("window.foundationAPI.updatePreferences({theme:'invalid'}).then(()=>{throw new Error('Invalid theme accepted')},()=>true)");
  const click = label => evaluate(`Array.from(document.querySelectorAll('nav button')).find(button=>button.textContent===${JSON.stringify(label)}).click()`);
  await click('Settings');
  await waitFor("document.querySelector('.kc-page-heading h1').textContent==='Settings'");
  await waitFor("!document.querySelector('.kc-theme select').disabled");
  await evaluate("const select=document.querySelector('.kc-theme select'); select.value='dark'; select.dispatchEvent(new Event('change',{bubbles:true}));");
  await waitFor("document.querySelector('.kc-foundation').dataset.theme==='dark'");
  await waitFor("!document.querySelector('.kc-theme select').disabled");
  await screenshot('settings-dark.png');
  await window.loadURL(window.webContents.getURL());
  await waitFor("document.querySelector('.kc-page-heading h1')?.textContent==='Settings' && document.querySelector('.kc-foundation').dataset.theme==='dark'");
  await evaluate("const select=document.querySelector('.kc-theme select'); select.value='light'; select.dispatchEvent(new Event('change',{bubbles:true}));");
  await waitFor("document.querySelector('.kc-foundation').dataset.theme==='light' && !document.querySelector('.kc-theme select').disabled");
  await click('Products');
  await waitFor("document.querySelector('.kc-page-heading h1')?.textContent==='Products' && !document.querySelector('.kc-theme select').disabled");
  const imported = await evaluate('window.foundationAPI.loadCatalog()');
  if (imported.products.length !== 93 || imported.state.nextSku !== 100093) throw new Error('Catalog migration did not reconcile.');
  await evaluate(`(() => { const select=document.querySelector('.kc-catalog-tools select'); select.value='clothing'; select.dispatchEvent(new Event('change',{bubbles:true})); })()`);
  await waitFor("document.querySelectorAll('.kc-product-link').length===4");
  await evaluate("Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='Show sizes').click()");
  await waitFor("document.querySelectorAll('.kc-variant-row').length===3");
  await screenshot('products-light.png');
  await evaluate("document.querySelector('.kc-product-link').click()");
  await waitFor("!!document.querySelector('.kc-product-editor')");
  await evaluate(`(() => { const input=document.querySelector('[aria-label^="Purchase cost"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'100.00'); input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
  await evaluate("Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='Calculate').click()");
  await waitFor("!!document.querySelector('.kc-calculator')");
  await evaluate("document.querySelector('.kc-calculator').scrollIntoView({block:'center'})");
  await screenshot('calculator-light.png');
  await evaluate("Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='Apply to this size').click()");
  await waitFor("document.querySelector('[aria-label^=\"Selling price\"]').value==='130.00'");
  await evaluate("document.querySelector('.kc-product-editor').requestSubmit()");
  await waitFor("!document.querySelector('.kc-product-editor') && !document.querySelector('.kc-theme select').disabled");
  const saved = await evaluate('window.foundationAPI.loadCatalog()');
  if (saved.products.find(p=>p.sku==='100089').variants[0].sellingPricePaise !== 13000) throw new Error('Calculated price was not saved.');
  await window.loadURL(window.webContents.getURL());
  await waitFor("!!document.querySelector('.kc-product-link')");
  const reloaded = await evaluate('window.foundationAPI.loadCatalog()');
  if (reloaded.products.find(p=>p.sku==='100089').variants[0].sellingPricePaise !== 13000) throw new Error('Price was reset after reload.');
  const setInput = (selector, value) => evaluate(`(() => { const input=document.querySelector(${JSON.stringify(selector)}); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,${JSON.stringify(value)}); input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
  const press = label => evaluate(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent===${JSON.stringify(label)}).click()`);
  await click('Receive stock');
  await waitFor("!!document.querySelector('[role=combobox]') && !document.querySelector('.kc-theme select').disabled");
  await setInput('[role=combobox]', '100089');
  await waitFor("!!document.querySelector('.kc-stock-results button')");
  await evaluate("document.querySelector('.kc-stock-results button').click()");
  await waitFor("!!document.querySelector('[aria-label^=\"Receiving S\"]')");
  await setInput('[aria-label^="Receiving S"]', '5');
  await setInput('[aria-label^="Purchase cost S"]', '155');
  await setInput('[aria-label^="Receiving M"]', '3');
  await setInput('[aria-label^="Purchase cost M"]', '170');
  await press('Review stock entry');
  await waitFor("!!document.querySelector('.kc-stock-review') && !document.querySelector('.kc-theme select').disabled");
  await screenshot('receive-review.png');
  await press('Confirm stock entry');
  await waitFor("!document.querySelector('.kc-stock-review') && !document.querySelector('.kc-theme select').disabled");
  const received = await evaluate('window.foundationAPI.loadStock()');
  if (received.inventory.movements.length !== 2 || received.catalog.products.find(p=>p.sku==='100089').variants[0].stock !== 5) throw new Error('Receiving stock did not commit correctly.');
  await click('Adjust stock');
  await waitFor("document.querySelector('.kc-page-heading h1').textContent==='Adjust stock' && !document.querySelector('.kc-theme select').disabled");
  await setInput('[role=combobox]', '100089');
  await waitFor("!!document.querySelector('.kc-stock-results button')");
  await evaluate("document.querySelector('.kc-stock-results button').click()");
  await waitFor("!!document.querySelector('.kc-field-grid input')");
  await setInput('.kc-field-grid input', '4');
  await press('Review adjustment');
  await waitFor("!!document.querySelector('.kc-stock-review') && !document.querySelector('.kc-theme select').disabled");
  await screenshot('adjust-review.png');
  await press('Save adjustment');
  await waitFor("!document.querySelector('.kc-stock-review') && !document.querySelector('.kc-theme select').disabled");
  await click('Stock history');
  await waitFor("document.querySelectorAll('.kc-history-table tbody tr').length===3 && !document.querySelector('.kc-theme select').disabled");
  if (!await evaluate("document.querySelector('.kc-history-table tbody tr').textContent.includes('Adjustment')")) throw new Error('Newest movement is not first.');
  await evaluate("(() => { const select=document.querySelector('.kc-theme select'); select.value='dark'; select.dispatchEvent(new Event('change',{bubbles:true})); })()");
  await waitFor("document.querySelector('.kc-foundation').dataset.theme==='dark' && !document.querySelector('.kc-theme select').disabled");
  await screenshot('stock-history-dark.png');
  await window.loadURL(window.webContents.getURL());
  await waitFor("document.querySelectorAll('.kc-history-table tbody tr').length===3");
  const finalStock = await evaluate('window.foundationAPI.loadStock()');
  if (finalStock.catalog.products.find(p=>p.sku==='100089').variants[0].stock !== 4) throw new Error('Stock correction did not persist.');
  window.setSize(760, 700);
  await new Promise(resolve => setTimeout(resolve, 100));
  const overflow = await evaluate('document.documentElement.scrollWidth > window.innerWidth');
  if (overflow) throw new Error('Horizontal overflow at compact laptop width.');
  await screenshot('stock-compact.png');
  console.log(JSON.stringify({ result: 'Desktop smoke passed', checks: ['isolated bridge', 'invalid IPC input rejected', 'navigation', 'theme saved', 'screen/theme restored on reload', '93-product import', 'size rows', 'calculator applied and saved', 'price survives reload', 'stock review/save', 'stock correction', 'latest-first history', 'stock survives reload', 'compact width'], screenshots: directory }));
};
